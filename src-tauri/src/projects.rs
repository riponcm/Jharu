/// The rating the user saw, sent back so that anything that got worse since
/// is skipped.
#[derive(Deserialize, Clone, Copy)]
#[serde(rename_all = "snake_case")]
pub enum Seen {
    Safe,
    Caution,
    Risky,
}

impl Seen {
    fn safety(self) -> Safety {
        match self {
            Seen::Safe => Safety::Safe,
            Seen::Caution => Safety::Caution,
            Seen::Risky => Safety::Risky,
        }
    }
}

#[derive(Deserialize, Clone)]
pub struct RemoveRequest {
    pub project: String,
    pub kind: Kind,
    pub paths: Vec<String>,
    pub expected: Seen,
}

#[derive(Serialize, Default)]
pub struct RemoveOutcome {
    pub freed_bytes: u64,
    /// Ids (first paths) of what went to the Trash.
    pub removed: Vec<String>,
    pub already_gone: Vec<String>,
    pub skipped: Vec<String>,
    pub errors: Vec<String>,
    pub cancelled: bool,
    /// Requests never started because the user cancelled.
    pub not_started: usize,
}

enum Skip {
    Gone,
    Reason(String),
}

/// Checks a request against the disk as it is now. Returns the folders to
/// move, or why not. Nothing the scan said is trusted: the folder must still
/// be a real folder (not a link), still sit where its project confirms it,
/// and still rate no worse than the user saw.
fn prepare(r: &RemoveRequest, facts: &ProjFacts) -> Result<Vec<PathBuf>, Skip> {
    let why = |s: String| Err(Skip::Reason(s));
    let project = PathBuf::from(&r.project);
    let label = r.kind.label();
    if !project.is_absolute() || r.paths.is_empty() {
        return why(format!("{label}: the request is incomplete"));
    }
    let mut live = vec![];
    for p in &r.paths {
        let path = PathBuf::from(p);
        if !path.is_absolute() || !is_inside(&path, &project) {
            return why(format!("{p}: not removed because it is not inside the project"));
        }
        let (Some(name), Some(parent)) = (path.file_name().map(|n| n.to_string_lossy().into_owned()), path.parent()) else {
            return why(format!("{p}: not a folder path"));
        };
        match path.symlink_metadata() {
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => continue,
            Err(e) => return why(format!("{p}: not removed because Jharu cannot look at it ({e})")),
            Ok(m) if m.file_type().is_symlink() || !m.is_dir() => {
                return why(format!("{p}: not removed because it is a link or not a folder"));
            }
            Ok(_) => {}
        }
        match recognise(parent, &name, &list_names(parent)) {
            Some((kind, _)) if kind == r.kind => {}
            _ => return why(format!("{p}: not removed because it is no longer recognised as a {}", label.to_lowercase())),
        }
        if !r.kind.floats() && path_key(parent) != path_key(&project) {
            return why(format!("{p}: not removed because it does not sit directly in the project"));
        }
        // The checks above read the path as written. A junction or symlink
        // higher up (project/packages -> elsewhere) would still lead out of
        // the project, so the real locations must agree too.
        match (std::fs::canonicalize(&path), std::fs::canonicalize(&project)) {
            (Ok(real), Ok(real_project)) if is_inside(&real, &real_project) => {}
            _ => return why(format!("{p}: not removed because a link inside the project leads it elsewhere")),
        }
        live.push(path);
    }
    if live.is_empty() {
        return Err(Skip::Gone);
    }
    if langs_in(&list_names(&project)).is_empty() {
        return why(format!("{}: the project's own files are gone, so Jharu can no longer tell what this belongs to", project.display()));
    }
    let now = assess(r.kind, &project, &live, &[], facts);
    let name = live[0].file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    if now.in_use {
        let detail: Vec<&str> = now.reasons.iter().filter(|x| x.level != Level::Ok).map(|x| x.text.as_str()).collect();
        return why(format!("{} {name}: in use — {}", project.display(), detail.join(" ")));
    }
    if now.safety > r.expected.safety() {
        let detail: Vec<&str> = now.reasons.iter().filter(|x| x.level != Level::Ok).map(|x| x.text.as_str()).collect();
        return why(format!("{} {name}: changed since the scan — {}", project.display(), detail.join(" ")));
    }
    Ok(live)
}

/// `dispose` moves one folder away: the Trash / Recycle Bin in the app, a
/// plain delete of the fixture in tests, so tests never fill the real bin.
fn remove_impl(
    requests: &[RemoveRequest],
    cancelled: impl Fn() -> bool,
    mut progress: impl FnMut(usize, usize, &str),
    dispose: impl Fn(&Path) -> Result<(), String>,
) -> RemoveOutcome {
    let mut out = RemoveOutcome::default();
    let total = requests.len();
    let mut facts = ProjFacts::gather();
    let mut gathered = Instant::now();
    for (n, r) in requests.iter().enumerate() {
        if cancelled() {
            out.cancelled = true;
            out.not_started = total - n;
            break;
        }
        let id = r.paths.first().cloned().unwrap_or_default();
        progress(n, total, &id);
        if gathered.elapsed() > FACTS_MAX_AGE {
            facts = ProjFacts::gather();
            gathered = Instant::now();
        }
        let live = match prepare(r, &facts) {
            Ok(live) => live,
            Err(Skip::Gone) => {
                out.already_gone.push(id);
                continue;
            }
            Err(Skip::Reason(why)) => {
                out.skipped.push(why);
                continue;
            }
        };
        let mut moved = false;
        for path in live {
            // What deleting really releases, measured before it goes.
            let size = crate::usage::reclaimable(&path);
            match dispose(&path) {
                Ok(()) if !path.exists() => {
                    out.freed_bytes += size;
                    moved = true;
                }
                Ok(()) => out.errors.push(format!("{}: still there after moving it to the {BIN}", path.display())),
                // Windows moves a folder whole or not at all; a file held open
                // by a program shows up only as "aborted".
                Err(e) if path.exists() && e.contains("aborted") => out.skipped.push(format!(
                    "{}: a file inside is open in another program (an editor, terminal or dev server), so nothing was moved. Close it and try again.",
                    path.display()
                )),
                Err(e) => out.errors.push(format!("{}: {e}", path.display())),
            }
        }
        if moved {
            out.removed.push(id);
        }
    }
    progress(total - out.not_started, total, "");
    out
}

/// Moves build folders to the Trash / Recycle Bin, re-checking each one first.
#[tauri::command]
pub async fn remove_build_folders(app: tauri::AppHandle, items: Vec<RemoveRequest>, token: String) -> Result<RemoveOutcome, String> {
    tauri::async_runtime::spawn_blocking(move || {
        let out = remove_impl(
            &items,
            || is_cancelled(&token),
            |done, total, current| {
                let _ = app.emit(
                    "build-folders-progress",
                    Progress { token: token.clone(), phase: "remove".into(), done, total, current: current.into() },
                );
            },
            |path| trash::delete(path).map_err(|e| e.to_string()),
        );
        cancel_set().lock().unwrap().remove(&token);
        out
    })
    .await
    .map_err(|e| e.to_string())
}

