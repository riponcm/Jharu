/// The project types a folder's entries show.
fn langs_in(names: &HashSet<String>) -> Vec<Lang> {
    let has = |f: &str| names.contains(f);
    let mut langs = vec![];
    if has("package.json") {
        langs.push(Lang::Node);
    }
    if has("Cargo.toml") {
        langs.push(Lang::Rust);
    }
    if has("pyproject.toml") || has("setup.py") || has("setup.cfg") || has("requirements.txt") || has("Pipfile") {
        langs.push(Lang::Python);
    }
    if has("build.gradle") || has("build.gradle.kts") || has("settings.gradle") || has("settings.gradle.kts") {
        langs.push(Lang::Gradle);
    }
    if has("pom.xml") {
        langs.push(Lang::Maven);
    }
    if has("pubspec.yaml") {
        langs.push(Lang::Dart);
    }
    if has("Podfile") {
        langs.push(Lang::Ios);
    }
    if has("CMakeLists.txt") {
        langs.push(Lang::CMake);
    }
    langs
}

// ---------------------------------------------------------------- paths

/// Comparable form of a path: separators unified, no trailing slash, and
/// case-folded where the file system ignores case.
fn path_key(p: &Path) -> String {
    let s = p.to_string_lossy().replace('\\', "/");
    let s = s.trim_end_matches('/').to_string();
    if cfg!(any(target_os = "windows", target_os = "macos")) {
        s.to_lowercase()
    } else {
        s
    }
}

fn is_inside(child: &Path, parent: &Path) -> bool {
    let (c, p) = (path_key(child), path_key(parent));
    c.len() > p.len() && c.starts_with(&p) && c.as_bytes()[p.len()] == b'/'
}

fn days_since(t: SystemTime) -> Option<u64> {
    SystemTime::now().duration_since(t).ok().map(|d| d.as_secs() / 86_400)
}

/// Names of the entries directly inside `dir` (empty when unreadable).
fn list_names(dir: &Path) -> HashSet<String> {
    std::fs::read_dir(dir)
        .map(|rd| rd.flatten().map(|e| e.file_name().to_string_lossy().into_owned()).collect())
        .unwrap_or_default()
}

/// Folders the walk never enters: hidden folders, the OS, and places where
/// projects do not live. Build folders are recognised before this applies.
fn skip_dir(name: &str) -> bool {
    if name.starts_with('.') || name.starts_with('$') || name == "node_modules" {
        return true;
    }
    matches!(
        name.to_lowercase().as_str(),
        "appdata" | "library" | "applications" | "windows" | "program files" | "program files (x86)"
            | "programdata" | "system volume information" | "recovery" | "movies" | "music"
            | "pictures" | "videos" | "photos library.photoslibrary"
    )
}

/// Why Jharu will not search inside this folder, if it must not.
fn protected_root(path: &Path) -> Option<&'static str> {
    let mut os: Vec<PathBuf> = vec![];
    #[cfg(target_os = "windows")]
    for var in ["SystemRoot", "ProgramFiles", "ProgramFiles(x86)", "ProgramData"] {
        if let Some(v) = std::env::var_os(var) {
            os.push(PathBuf::from(v));
        }
    }
    #[cfg(not(target_os = "windows"))]
    for p in ["/System", "/Library", "/Applications", "/usr", "/bin", "/sbin", "/etc", "/var", "/private", "/dev", "/proc", "/sys", "/opt"] {
        os.push(PathBuf::from(p));
    }
    if os.iter().any(|o| path_key(o) == path_key(path) || is_inside(path, o)) {
        return Some("it is part of the operating system");
    }
    if path.parent().is_none() && cfg!(not(target_os = "windows")) {
        return Some("it is the root of the disk");
    }
    None
}

// ---------------------------------------------------------------- .gitignore

/// Matches one path segment against a pattern with `*` and `?`.
fn glob(pattern: &str, text: &str) -> bool {
    fn go(p: &[char], t: &[char]) -> bool {
        match p.split_first() {
            None => t.is_empty(),
            Some(('*', rest)) => (0..=t.len()).any(|n| go(rest, &t[n..])),
            Some(('?', rest)) => !t.is_empty() && go(rest, &t[1..]),
            Some((c, rest)) => t.first() == Some(c) && go(rest, &t[1..]),
        }
    }
    let (p, t): (Vec<char>, Vec<char>) = (pattern.chars().collect(), text.chars().collect());
    go(&p, &t)
}

/// Does one .gitignore line name the folder at `rel` (its path from the
/// .gitignore's directory, with forward slashes)? Handles plain names,
/// anchored paths, `*` and `**/`; the unusual pattern forms are ignored,
/// which only ever means a folder is not offered.
fn pattern_matches(pattern: &str, rel: &str) -> bool {
    let trimmed = pattern.trim_end_matches('/');
    let (body, floating) = if let Some(rest) = trimmed.strip_prefix("**/") {
        (rest, true)
    } else if let Some(rest) = trimmed.strip_prefix('/') {
        (rest, false)
    } else {
        (trimmed, !trimmed.contains('/'))
    };
    if body.is_empty() {
        return false;
    }
    let pat: Vec<&str> = body.split('/').collect();
    let path: Vec<&str> = rel.split('/').collect();
    if floating {
        path.len() >= pat.len() && pat.iter().zip(&path[path.len() - pat.len()..]).all(|(p, s)| glob(p, s))
    } else {
        path.len() == pat.len() && pat.iter().zip(&path).all(|(p, s)| glob(p, s))
    }
}

/// Whether a .gitignore's text ends up ignoring `rel`: the last line that
/// matches wins, and `!` un-ignores.
fn ignores(text: &str, rel: &str) -> bool {
    let mut ignored = false;
    for line in text.lines() {
        let l = line.trim();
        if l.is_empty() || l.starts_with('#') {
            continue;
        }
        let (negated, pattern) = match l.strip_prefix('!') {
            Some(p) => (true, p),
            None => (false, l),
        };
        if pattern_matches(pattern, rel) {
            ignored = !negated;
        }
    }
    ignored
}

/// The .gitignore that lists `dir/name`. Git applies the .gitignore files
/// from `dir` up to the repository's root, so those are read; outside a
/// repository only `dir`'s own counts.
fn gitignored_by(dir: &Path, name: &str) -> Option<PathBuf> {
    let top = dir.ancestors().take(9).find(|a| a.join(".git").exists()).unwrap_or(dir);
    let mut rel = name.to_string();
    for ancestor in dir.ancestors() {
        let file = ancestor.join(".gitignore");
        if let Ok(text) = std::fs::read_to_string(&file) {
            if ignores(&text, &rel) {
                return Some(file);
            }
        }
        if path_key(ancestor) == path_key(top) {
            break;
        }
        if let Some(n) = ancestor.file_name() {
            rel = format!("{}/{}", n.to_string_lossy(), rel);
        }
    }
    None
}

fn has_build_script(dir: &Path) -> bool {
    std::fs::read_to_string(dir.join("package.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .is_some_and(|v| v.get("scripts").and_then(|s| s.get("build")).is_some())
}

// ---------------------------------------------------------------- recognising

/// What the folder `name` inside `dir` is, if the entries around it confirm
/// it, with the evidence in words. `sibs` are the names of everything in `dir`.
/// This is the single gate: the scan uses it to offer a folder, and removal
/// uses it again to be sure the folder is still what it was.
fn recognise(dir: &Path, name: &str, sibs: &HashSet<String>) -> Option<(Kind, String)> {
    let has = |f: &str| sibs.contains(f);
    let path = dir.join(name);
    let node = has("package.json");
    let gradle = langs_in(sibs).contains(&Lang::Gradle);
    let python_pkg = has("pyproject.toml") || has("setup.py") || has("setup.cfg");

    let beside = |file: &str| format!("{file} sits next to it");
    match name {
        "node_modules" if node => return Some((Kind::NodeModules, beside("package.json"))),
        ".next" if node => return Some((Kind::Next, beside("package.json"))),
        ".nuxt" if node => return Some((Kind::Nuxt, beside("package.json"))),
        ".svelte-kit" if node => return Some((Kind::SvelteKit, beside("package.json"))),
        ".turbo" if node => return Some((Kind::Turbo, beside("package.json"))),
        ".parcel-cache" if node => return Some((Kind::ParcelCache, beside("package.json"))),
        ".dart_tool" if has("pubspec.yaml") => return Some((Kind::DartTool, beside("pubspec.yaml"))),
        "Pods" if has("Podfile") => return Some((Kind::Pods, beside("Podfile"))),
        ".gradle" if gradle => return Some((Kind::GradleCache, "a Gradle build file sits next to it".into())),
        ".pytest_cache" => return Some((Kind::PytestCache, "pytest names this folder for its cache".into())),
        ".mypy_cache" => return Some((Kind::MypyCache, "mypy names this folder for its cache".into())),
        ".ruff_cache" => return Some((Kind::RuffCache, "Ruff names this folder for its cache".into())),
        ".tox" if python_pkg || has("tox.ini") => {
            return Some((Kind::Tox, "tox.ini or the Python project files sit next to it".into()))
        }
        ".venv" | "venv" if path.join("pyvenv.cfg").is_file() => {
            return Some((Kind::Venv, "it holds pyvenv.cfg, which Python writes into every virtual environment".into()))
        }
        "__pycache__" if only_bytecode(&path) => {
            return Some((Kind::PyCache, "it holds nothing but compiled .pyc files".into()))
        }
        "target" => {
            if has("Cargo.toml") {
                if path.join("CACHEDIR.TAG").is_file() {
                    return Some((Kind::RustTarget, "Cargo.toml sits next to it and it holds CACHEDIR.TAG, the marker Cargo writes into build output".into()));
                }
                if path.join("debug").is_dir() || path.join("release").is_dir() {
                    return Some((Kind::RustTarget, "Cargo.toml sits next to it and it holds Cargo's debug or release folders".into()));
                }
            }
            if has("pom.xml")
                && ["classes", "test-classes", "maven-status", "maven-archiver", "surefire-reports"]
                    .iter()
                    .any(|d| path.join(d).is_dir())
            {
                return Some((Kind::MavenTarget, "pom.xml sits next to it and it holds Maven's compiled classes".into()));
            }
        }
        "build" if gradle => return Some((Kind::GradleBuild, "a Gradle build file sits next to it".into())),
        _ => {}
    }

    if has("CMakeLists.txt") && cmake_source_is(&path, dir) {
        return Some((Kind::CMake, "it holds a CMakeCache.txt whose source folder is this project".into()));
    }

    if (name == "dist" || name == "build") && (node && has_build_script(dir) || python_pkg || has("pubspec.yaml")) {
        if let Some(file) = gitignored_by(dir, name) {
            return Some((Kind::BuildOutput, format!("{} lists it, so git treats it as generated", file.display())));
        }
    }
    None
}

/// A `__pycache__` holds only compiled bytecode; anything else in there is
/// somebody's file.
fn only_bytecode(dir: &Path) -> bool {
    let Ok(rd) = std::fs::read_dir(dir) else { return false };
    rd.flatten().all(|e| {
        let n = e.file_name().to_string_lossy().into_owned();
        e.file_type().is_ok_and(|t| t.is_file()) && (n.ends_with(".pyc") || n.ends_with(".pyo") || n.contains(".pyc."))
    })
}

/// True when `build/CMakeCache.txt` was configured from `source`.
fn cmake_source_is(build: &Path, source: &Path) -> bool {
    let Ok(text) = std::fs::read_to_string(build.join("CMakeCache.txt")) else { return false };
    text.lines()
        .find_map(|l| l.strip_prefix("CMAKE_HOME_DIRECTORY:INTERNAL="))
        .is_some_and(|home| path_key(Path::new(home.trim())) == path_key(source))
}

// ---------------------------------------------------------------- discovery

struct Candidate {
    path: PathBuf,
    parent: PathBuf,
    kind: Kind,
    evidence: String,
}

#[derive(Default)]
struct Found {
    /// Every folder that holds a project's marker files, by path key.
    projects: BTreeMap<String, (PathBuf, Vec<Lang>)>,
    candidates: Vec<Candidate>,
}

type Children = Vec<jwalk::Result<jwalk::DirEntry<((), ())>>>;

/// Looks at one folder's entries: notes the project it holds, notes the
/// build folders in it, and prunes the walk so it never enters a build
/// folder, a hidden folder or the OS.
fn visit_dir(dir: &Path, children: &mut Children, found: &Mutex<Found>) {
    let sibs: HashSet<String> = children.iter().flatten().map(|e| e.file_name.to_string_lossy().into_owned()).collect();
    let langs = langs_in(&sibs);
    let mut candidates = vec![];
    children.retain(|c| {
        let Ok(e) = c else { return true };
        if !e.file_type().is_dir() {
            return false;
        }
        let name = e.file_name.to_string_lossy();
        if let Some((kind, evidence)) = recognise(dir, &name, &sibs) {
            candidates.push(Candidate { path: dir.join(&*name), parent: dir.to_path_buf(), kind, evidence });
            return false;
        }
        !skip_dir(&name)
    });
    if !langs.is_empty() || !candidates.is_empty() {
        let mut f = found.lock().unwrap();
        if !langs.is_empty() {
            f.projects.insert(path_key(dir), (dir.to_path_buf(), langs));
        }
        f.candidates.extend(candidates);
    }
}

fn discover(roots: &[PathBuf], found: &std::sync::Arc<Mutex<Found>>, cancelled: &dyn Fn() -> bool, progress: &dyn Fn(&str)) {
    for root in roots {
        if !root.is_dir() {
            continue;
        }
        let shared = found.clone();
        let walker = crate::walk::walk(root)
            .max_depth(SEARCH_DEPTH)
            .skip_hidden(false)
            .follow_links(false)
            .process_read_dir(move |_, dir, _, children| visit_dir(dir, children, &shared));
        let mut seen = 0usize;
        for entry in walker.into_iter().flatten() {
            seen += 1;
            if seen % 400 == 0 {
                if cancelled() {
                    return;
                }
                progress(&entry.path().to_string_lossy());
            }
        }
    }
}

/// One thing the user can remove: a build folder, or all of a project's
/// `__pycache__` folders together.
struct Target {
    kind: Kind,
    project: PathBuf,
    paths: Vec<PathBuf>,
    evidence: Vec<String>,
}

/// Attaches each candidate to its project and groups the `__pycache__`
/// folders of one project into one entry.
fn resolve(found: &Found) -> Vec<Target> {
    let mut targets: Vec<Target> = vec![];
    let mut pycache: HashMap<String, usize> = HashMap::new();
    let mut seen: HashSet<String> = HashSet::new();
    for c in &found.candidates {
        if !seen.insert(path_key(&c.path)) {
            continue;
        }
        let project = if c.kind.floats() {
            c.parent.ancestors().find(|a| found.projects.contains_key(&path_key(a)))
        } else {
            found.projects.contains_key(&path_key(&c.parent)).then_some(c.parent.as_path())
        };
        let Some(project) = project else { continue };
        if c.kind == Kind::PyCache {
            if let Some(&i) = pycache.get(&path_key(project)) {
                targets[i].paths.push(c.path.clone());
                continue;
            }
            pycache.insert(path_key(project), targets.len());
        }
        targets.push(Target { kind: c.kind, project: project.to_path_buf(), paths: vec![c.path.clone()], evidence: vec![c.evidence.clone()] });
    }
    for t in &mut targets {
        t.paths.sort();
    }
    targets
}

// ---------------------------------------------------------------- live facts

/// Programs that build, serve or test a project. A runtime such as `node`
/// runs for every reason, so these only count when the process was started
/// inside the project (see [`ProjFacts::using`]).
const DEV_TOOLS: &[&str] = &[
    "node", "npm", "npx", "pnpm", "yarn", "bun", "deno", "vite", "next", "nuxt", "webpack", "esbuild", "tsc",
    "nodemon", "turbo", "cargo", "rustc", "rust-analyzer", "cargo-watch", "python", "python3", "pythonw", "uvicorn",
    "gunicorn", "flask", "pytest", "jupyter", "jupyter-lab", "pip", "uv", "poetry", "tox", "mypy", "ruff", "java",
    "gradle", "gradlew", "dart", "flutter", "cmake", "ninja", "make", "msbuild", "cl", "pod", "xcodebuild",
];

struct Proc {
    name: String,
    cwd: Option<PathBuf>,
    /// Command-line arguments that are absolute paths.
    args: Vec<PathBuf>,
}

/// What is running right now: the shared facts plus where each program was
/// started, which tells a dev server from an unrelated `node`.
struct ProjFacts {
    base: Facts,
    procs: Vec<Proc>,
}

impl ProjFacts {
    fn gather() -> ProjFacts {
        use sysinfo::UpdateKind;
        let mut sys = sysinfo::System::new();
        sys.refresh_processes_specifics(
            sysinfo::ProcessesToUpdate::All,
            true,
            sysinfo::ProcessRefreshKind::nothing()
                .with_exe(UpdateKind::Always)
                .with_cmd(UpdateKind::Always)
                .with_cwd(UpdateKind::Always),
        );
        let mut base = Facts::default();
        let mut procs = vec![];
        for p in sys.processes().values() {
            let lower = p.name().to_string_lossy().to_lowercase();
            let name = lower.strip_suffix(".exe").map(String::from).unwrap_or(lower);
            base.running.insert(name.clone());
            if let Some(exe) = p.exe() {
                base.exes.push(exe.to_path_buf());
            }
            let args = p.cmd().iter().map(PathBuf::from).filter(|a| a.is_absolute()).collect();
            procs.push(Proc { name, cwd: p.cwd().map(Path::to_path_buf), args });
        }
        ProjFacts { base, procs }
    }

    /// Programs that may be using `folder` of `project` right now: anything
    /// running from inside the folder, and a build tool or dev server that
    /// was started inside the project.
    fn using(&self, project: &Path, folder: &Path) -> Vec<String> {
        let mut names = self.base.running_from(folder);
        let inside = |p: &Path| path_key(p) == path_key(project) || is_inside(p, project);
        // A dev server started at a monorepo root uses its packages' folders
        // too, so a tool working in a parent that is itself a project counts.
        let parent_project = |p: &Path| is_inside(project, p) && !langs_in(&list_names(p)).is_empty();
        for p in &self.procs {
            let cwd_counts = p.cwd.as_deref().is_some_and(|c| inside(c) || parent_project(c));
            if DEV_TOOLS.contains(&p.name.as_str()) && (cwd_counts || p.args.iter().any(|a| inside(a))) {
                names.push(p.name.clone());
            }
        }
        names.sort();
        names.dedup();
        names
    }
}

/// Lock files that the tool for this kind holds while it works there.
fn lock_files(kind: Kind, path: &Path) -> Vec<PathBuf> {
    match kind {
        Kind::NodeModules => [".package-lock.json", ".yarn-integrity", ".modules.yaml"].iter().map(|f| path.join(f)).collect(),
        Kind::RustTarget => vec![path.join(".cargo-lock"), path.join("debug").join(".cargo-lock"), path.join("release").join(".cargo-lock")],
        Kind::GradleCache => {
            let mut locks = vec![path.join("buildOutputCleanup").join("buildOutputCleanup.lock")];
            if let Ok(rd) = std::fs::read_dir(path) {
                for v in rd.flatten().filter(|e| e.file_type().is_ok_and(|t| t.is_dir())) {
                    locks.push(v.path().join("checksums").join("checksums.lock"));
                    locks.push(v.path().join("fileHashes").join("fileHashes.lock"));
                }
            }
            locks
        }
        _ => vec![],
    }
}

// ---------------------------------------------------------------- rating

struct Assessment {
    safety: Safety,
    reasons: Vec<Reason>,
    /// A program is using it, or its lock is held: never removed meanwhile.
    in_use: bool,
    rebuild: String,
}

fn node_pm(files: &HashSet<String>) -> &'static str {
    if files.contains("pnpm-lock.yaml") {
        "pnpm"
    } else if files.contains("yarn.lock") {
        "yarn"
    } else if files.contains("bun.lockb") || files.contains("bun.lock") {
        "bun"
    } else {
        "npm"
    }
}

/// How a virtualenv's packages would be installed again, from what the
/// project keeps, or `None` when nothing says what was installed.
fn venv_reinstall(files: &HashSet<String>, name: &str) -> Option<String> {
    let has = |f: &str| files.contains(f);
    if has("uv.lock") {
        Some("uv sync".into())
    } else if has("poetry.lock") {
        Some("poetry install".into())
    } else if has("Pipfile") || has("Pipfile.lock") {
        Some("pipenv install".into())
    } else if has("requirements.txt") {
        Some(format!("python -m venv {name}, then pip install -r requirements.txt"))
    } else if has("pyproject.toml") || has("setup.py") {
        Some(format!("python -m venv {name}, then pip install -e ."))
    } else {
        None
    }
}

/// The rating for removing `kind` at `paths` in `project`, with the reasons.
/// `evidence` is why it was recognised (empty on a re-check at removal).
fn assess(kind: Kind, project: &Path, paths: &[PathBuf], evidence: &[String], facts: &ProjFacts) -> Assessment {
    let files = list_names(project);
    let mut safety = Safety::Safe;
    let mut reasons: Vec<Reason> = vec![];
    let mut note = |level: Level, at_least: Safety, text: String| {
        if at_least > safety {
            safety = at_least;
        }
        reasons.push(Reason { level, text });
    };
    let first = paths.first().cloned().unwrap_or_default();
    let name = first.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default();
    let pm = node_pm(&files);

    for e in evidence {
        note(Level::Ok, Safety::Safe, format!("Recognised as {}: {e}.", kind.label().to_lowercase()));
    }

    // What clearing it loses, and what brings it back.
    let rebuild: String = match kind {
        Kind::NodeModules | Kind::Pods => {
            let (cmd, lock) = if kind == Kind::NodeModules {
                let lock = ["package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "bun.lock"]
                    .into_iter()
                    .find(|l| files.contains(*l));
                (format!("{pm} install"), lock)
            } else {
                ("pod install".to_string(), files.contains("Podfile.lock").then_some("Podfile.lock"))
            };
            note(
                Level::Warn,
                Safety::Safe,
                format!("Does not come back by itself: run `{cmd}` before the project builds again (needs a network connection)."),
            );
            match lock {
                Some(l) => note(Level::Ok, Safety::Safe, format!("{l} pins the exact versions, so `{cmd}` brings back the same ones.")),
                None => note(
                    Level::Warn,
                    Safety::Caution,
                    "There is no lockfile next to it, so a reinstall may fetch newer versions than the ones you have now.".into(),
                ),
            }
            cmd
        }
        Kind::Venv => {
            match venv_reinstall(&files, &name) {
                Some(how) => note(
                    Level::Warn,
                    Safety::Caution,
                    format!("Needs a reinstall: `{how}`. Anything you installed by hand and did not list in the project is lost."),
                ),
                None => note(
                    Level::Bad,
                    Safety::Risky,
                    format!("The project has no requirements file, lockfile or pyproject.toml, so Jharu cannot tell which packages you installed here. Once the {BIN} is emptied they are gone."),
                ),
            }
            venv_reinstall(&files, &name).unwrap_or_else(|| "(unknown: nothing lists the packages)".into())
        }
        Kind::CMake => {
            note(
                Level::Warn,
                Safety::Caution,
                "CMakeCache.txt remembers the options you configured with (-D flags, generator, compiler). Rebuilding needs them again.".into(),
            );
            format!("cmake -S . -B {name} && cmake --build {name}")
        }
        other => {
            let (cmd, what) = match other {
                Kind::RustTarget => ("cargo build".to_string(), "compiler output"),
                Kind::MavenTarget => ("mvn package".to_string(), "compiler output"),
                Kind::Next | Kind::Nuxt | Kind::SvelteKit | Kind::Turbo | Kind::ParcelCache => {
                    (format!("{pm} run build"), "build output and caches")
                }
                Kind::BuildOutput => {
                    let cmd = if files.contains("package.json") {
                        format!("{pm} run build")
                    } else if files.contains("pubspec.yaml") {
                        "flutter build".to_string()
                    } else {
                        "python -m build".to_string()
                    };
                    (cmd, "build output")
                }
                Kind::PyCache => ("python".to_string(), "compiled bytecode"),
                Kind::PytestCache => ("pytest".to_string(), "cached test results"),
                Kind::MypyCache => ("mypy .".to_string(), "cached type-check results"),
                Kind::RuffCache => ("ruff check .".to_string(), "cached lint results"),
                Kind::Tox => ("tox".to_string(), "test environments tox creates"),
                Kind::GradleBuild | Kind::GradleCache => {
                    let cmd = if files.contains("gradlew") || files.contains("gradlew.bat") {
                        if cfg!(windows) { "gradlew build" } else { "./gradlew build" }
                    } else {
                        "gradle build"
                    };
                    (cmd.to_string(), "build output and caches")
                }
                Kind::DartTool => {
                    let flutter = std::fs::read_to_string(project.join("pubspec.yaml")).is_ok_and(|t| t.lines().any(|l| l.trim_end() == "flutter:"));
                    (if flutter { "flutter pub get" } else { "dart pub get" }.to_string(), "package resolution data")
                }
                _ => unreachable!(),
            };
            note(
                Level::Ok,
                Safety::Safe,
                format!("Comes back by itself: `{cmd}` creates it again. It holds only {what}, nothing of your own."),
            );
            cmd
        }
    };

    // Whether a program is using it at this moment.
    let mut using: Vec<String> = vec![];
    for p in paths {
        using.extend(facts.using(project, p));
    }
    using.sort();
    using.dedup();
    let locked = paths.iter().flat_map(|p| lock_files(kind, p)).find(|l| lock_held(l));
    let in_use = !using.is_empty() || locked.is_some();
    if !using.is_empty() {
        note(
            Level::Warn,
            Safety::Caution,
            format!(
                "{} is running from inside this project right now and may be using it. Close it first; otherwise Jharu leaves it in place.",
                using.join(", ")
            ),
        );
    } else if locked.is_some() {
        note(Level::Warn, Safety::Caution, "Its lock file is held, so a build tool is working in it right now. Try again when it finishes.".into());
    } else {
        note(Level::Ok, Safety::Safe, "Not in use right now: no build tool or dev server is running from this project, and its lock files are free.".into());
    }

    Assessment { safety, reasons, in_use, rebuild }
}

