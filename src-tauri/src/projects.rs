    #[test]
    fn links_are_never_followed_or_removed() {
        let fx = Fixture::new("link");
        fx.file("proj/package.json", "{}");
        fx.file("proj/package-lock.json", "{}");
        let target = fx.dir("elsewhere/real_modules");
        fs::write(target.join("keep.js"), "keep").unwrap();
        // A directory link named node_modules (symlinks may need privileges on Windows).
        #[cfg(unix)]
        let linked = std::os::unix::fs::symlink(&target, fx.root.join("proj/node_modules")).is_ok();
        #[cfg(windows)]
        let linked = std::os::windows::fs::symlink_dir(&target, fx.root.join("proj/node_modules")).is_ok();
        if !linked {
            eprintln!("skipped: cannot create a directory symlink here");
            return;
        }
        assert!(offered(&fx.scan(&idle()), &fx.root).is_empty(), "a linked node_modules is not a folder to remove");
        let out = remove_impl(
            &[RemoveRequest { project: fx.root.join("proj").to_string_lossy().into_owned(), kind: Kind::NodeModules, paths: vec![fx.root.join("proj/node_modules").to_string_lossy().into_owned()], expected: Seen::Safe }],
            || false,
            |_, _, _| {},
            gone,
        );
        assert!(out.removed.is_empty() && target.join("keep.js").exists());
    }

    /// A junction higher up inside the project must not let a removal reach
    /// a folder outside it. Junctions need no special rights on Windows.
    #[cfg(windows)]
    #[test]
    fn a_link_higher_up_cannot_lead_a_removal_out_of_the_project() {
        let fx = Fixture::new("junction");
        fx.file("mono/pyproject.toml", "[project]\nname = 'm'\n");
        let outside = fx.dir("outside/pkg");
        fs::write(outside.join("mod.py"), "x = 1").unwrap();
        let cache = fx.dir("outside/pkg/__pycache__");
        fs::write(cache.join("mod.cpython-312.pyc"), "pyc").unwrap();
        let made = std::process::Command::new("cmd")
            .args(["/c", "mklink", "/J"])
            .arg(fx.root.join("mono/packages"))
            .arg(fx.root.join("outside"))
            .output()
            .is_ok_and(|o| o.status.success());
        assert!(made, "could not create a junction");
        let req = RemoveRequest {
            project: fx.root.join("mono").to_string_lossy().into_owned(),
            kind: Kind::PyCache,
            paths: vec![fx.root.join("mono/packages/pkg/__pycache__").to_string_lossy().into_owned()],
            expected: Seen::Safe,
        };
        let out = remove_impl(&[req], || false, |_, _, _| {}, gone);
        assert!(cache.join("mod.cpython-312.pyc").exists(), "the folder behind the junction must stay");
        assert!(out.skipped.iter().any(|s| s.contains("link inside the project")), "{:?}", out.skipped);
        // Remove the junction itself, never what it points to.
        fs::remove_dir(fx.root.join("mono/packages")).unwrap();
    }

    /// `npm run dev` started at a monorepo root is using every package's
    /// node_modules, though its working folder is outside each package.
    #[test]
    fn a_dev_server_in_a_parent_project_means_in_use() {
        let fx = Fixture::new("monorepo");
        fx.file("repo/package.json", "{}");
        fx.file("repo/packages/web/package.json", "{}");
        let nm = fx.dir("repo/packages/web/node_modules");
        let mut facts = idle();
        facts.procs.push(Proc { name: "node".into(), cwd: Some(fx.root.join("repo")), args: vec![] });
        assert_eq!(facts.using(&fx.root.join("repo/packages/web"), &nm), vec!["node".to_string()]);
        // An unrelated parent that is no project does not count.
        let mut facts = idle();
        facts.procs.push(Proc { name: "node".into(), cwd: Some(fx.root.clone()), args: vec![] });
        assert!(facts.using(&fx.root.join("repo/packages/web"), &nm).is_empty());
    }

