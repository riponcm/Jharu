//! Build folders inside the user's projects: node_modules, Rust `target`,
//! `.next`, virtualenvs and the like. Like npkill or kondo, but a folder is
//! offered only when the project beside it confirms what it is, every one
//! carries a rating with the reasons for it, and removal goes to the
//! Recycle Bin / Trash.
//!
//! The evidence for each kind is deliberately specific. `node_modules` needs
//! a package.json next to it, `target` needs a Cargo.toml and Cargo's own
//! CACHEDIR.TAG (or debug/release folders), `dist` and `build` are offered
//! only when .gitignore says they are generated and the project has a build
//! command to make them again, a CMake folder must hold a CMakeCache.txt
//! whose source directory is the project. A folder that merely has the right
//! name, with nothing confirming it, is left alone.

