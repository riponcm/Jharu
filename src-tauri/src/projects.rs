/// Folder names that never count as a project's own source when looking for
/// when it last changed.
const NOT_SOURCE: &[&str] = &["node_modules", "target", "dist", "build", "out", "__pycache__", "venv", "env", "Pods", "obj"];

/// When a file of the project itself last changed, ignoring build folders.
fn source_modified(project: &Path, build_dirs: &HashSet<String>) -> Option<SystemTime> {
    let build_dirs = build_dirs.clone();
    let walker = crate::walk::walk(project).skip_hidden(true).follow_links(false).process_read_dir(move |_, dir, _, children| {
        children.retain(|c| {
            let Ok(e) = c else { return true };
            if !e.file_type().is_dir() {
                return true;
            }
            let name = e.file_name.to_string_lossy();
            !(NOT_SOURCE.contains(&&*name) || build_dirs.contains(&path_key(&dir.join(&*name))))
        });
    });
    let mut newest: Option<SystemTime> = None;
    let mut files = 0usize;
    for entry in walker.into_iter().flatten() {
        if !entry.file_type().is_file() {
            continue;
        }
        files += 1;
        if files > SOURCE_FILE_CAP {
            break;
        }
        if let Some(m) = entry.metadata().ok().and_then(|m| m.modified().ok()) {
            if newest.is_none_or(|n| m > n) {
                newest = Some(m);
            }
        }
    }
    newest
}

fn project_name(dir: &Path) -> String {
    let name = dir.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_else(|| dir.to_string_lossy().into_owned());
    let generic = matches!(name.to_lowercase().as_str(), "src-tauri" | "android" | "ios" | "app" | "backend" | "frontend" | "client" | "server" | "web" | "api");
    match dir.parent().and_then(|p| p.file_name()) {
        Some(parent) if generic => format!("{}/{}", parent.to_string_lossy(), name),
        _ => name,
    }
}

/// Day counts are the same for every folder of a project, so the rule for
/// pre-selecting lives here: only a safe folder of a project nobody has
/// touched for a month.
const PRESELECT_AFTER_DAYS: u64 = 30;

/// Where to look: the home folder plus the roots the user added, minus any
/// that are the OS or sit inside another root.
fn prepare_roots(extra: &[String]) -> (Vec<PathBuf>, Vec<String>) {
    let mut roots: Vec<PathBuf> = vec![];
    let mut skipped = vec![];
    match dirs::home_dir() {
        Some(h) => roots.push(h),
        None => skipped.push("Your home folder could not be found, so only the folders you added are searched.".into()),
    }
    for e in extra {
        let p = PathBuf::from(e.trim());
        if e.trim().is_empty() {
            continue;
        }
        if !p.is_absolute() || !p.is_dir() {
            skipped.push(format!("{e}: not an existing folder"));
        } else if let Some(why) = protected_root(&p) {
            skipped.push(format!("{e}: not searched because {why}"));
        } else {
            roots.push(p);
        }
    }
    let mut kept: Vec<PathBuf> = vec![];
    for r in &roots {
        let covered = roots.iter().any(|o| is_inside(r, o)) || kept.iter().any(|k| path_key(k) == path_key(r));
        if !covered {
            kept.push(r.clone());
        }
    }
    (kept, skipped)
}

/// Finds, measures and rates every build folder under `roots`. `None` when
/// cancelled part-way.
fn scan_roots(
    roots: &[PathBuf],
    facts: &ProjFacts,
    cancelled: &(dyn Fn() -> bool + Sync),
    progress: &(dyn Fn(&str, usize, usize, &str) + Sync),
) -> Option<Vec<ProjectItem>> {
    let found = std::sync::Arc::new(Mutex::new(Found::default()));
    discover(roots, &found, cancelled, &|cur| progress("find", 0, 0, cur));
    if cancelled() {
        return None;
    }
    let found = std::mem::take(&mut *found.lock().unwrap());
    let targets = resolve(&found);

    // Sizes and ratings, a few folders at a time.
    let total = targets.len();
    let next = AtomicUsize::new(0);
    let done = AtomicUsize::new(0);
    let measured: Mutex<Vec<(usize, BuildFolder)>> = Mutex::new(vec![]);
    std::thread::scope(|s| {
        for _ in 0..SIZE_WORKERS.min(total.max(1)) {
            s.spawn(|| loop {
                let i = next.fetch_add(1, Ordering::SeqCst);
                if i >= total || cancelled() {
                    break;
                }
                let t = &targets[i];
                let size: u64 = t.paths.iter().map(|p| crate::usage::reclaimable(p)).sum();
                let a = assess(t.kind, &t.project, &t.paths, &t.evidence_lines(), facts);
                let id = t.paths[0].to_string_lossy().into_owned();
                let folder = BuildFolder {
                    id: id.clone(),
                    paths: t.paths.iter().map(|p| p.to_string_lossy().into_owned()).collect(),
                    project: t.project.to_string_lossy().into_owned(),
                    kind: t.kind,
                    label: t.kind.label().to_string(),
                    size_bytes: size,
                    safety: a.safety,
                    reasons: a.reasons,
                    rebuild: a.rebuild,
                    in_use: a.in_use,
                    preselect: false,
                };
                measured.lock().unwrap().push((i, folder));
                progress("size", done.fetch_add(1, Ordering::SeqCst) + 1, total, &id);
            });
        }
    });
    if cancelled() {
        return None;
    }

    // Group by project.
    let mut by_project: BTreeMap<String, Vec<BuildFolder>> = BTreeMap::new();
    let mut measured = measured.into_inner().unwrap();
    measured.sort_by_key(|(i, _)| *i);
    for (_, f) in measured {
        if f.size_bytes > 0 {
            by_project.entry(path_key(Path::new(&f.project))).or_default().push(f);
        }
    }
    let build_dirs: HashSet<String> = by_project.values().flatten().flat_map(|f| f.paths.iter().map(|p| path_key(Path::new(p)))).collect();

    let mut projects = vec![];
    let count = by_project.len();
    for (n, (key, mut folders)) in by_project.into_iter().enumerate() {
        if cancelled() {
            return None;
        }
        let (dir, langs) = found.projects.get(&key).cloned().unwrap_or_default();
        progress("source", n, count, &dir.to_string_lossy());
        let days = source_modified(&dir, &build_dirs).and_then(days_since);
        for f in &mut folders {
            f.preselect = f.safety == Safety::Safe && !f.in_use && days.is_some_and(|d| d >= PRESELECT_AFTER_DAYS);
        }
        folders.sort_by(|a, b| b.size_bytes.cmp(&a.size_bytes));
        projects.push(ProjectItem {
            name: project_name(&dir),
            path: dir.to_string_lossy().into_owned(),
            project_type: langs.iter().map(|l| l.label()).collect::<Vec<_>>().join(" + "),
            source_modified_days: days,
            total_bytes: folders.iter().map(|f| f.size_bytes).sum(),
            folders,
        });
    }
    projects.sort_by(|a, b| b.total_bytes.cmp(&a.total_bytes));
    Some(projects)
}

impl Target {
    /// One evidence line per folder, or a count for grouped folders.
    fn evidence_lines(&self) -> Vec<String> {
        if self.paths.len() > 1 {
            vec![format!("{} folders, each holding nothing but compiled .pyc files", self.paths.len())]
        } else {
            self.evidence.clone()
        }
    }
}

fn report(roots: Vec<PathBuf>, skipped_roots: Vec<String>, projects: Vec<ProjectItem>) -> BuildReport {
    let all = projects.iter().flat_map(|p| &p.folders);
    let total_bytes = all.clone().map(|f| f.size_bytes).sum();
    let safe_bytes = all.filter(|f| f.safety == Safety::Safe && !f.in_use).map(|f| f.size_bytes).sum();
    BuildReport { total_bytes, safe_bytes, roots: roots.iter().map(|r| r.to_string_lossy().into_owned()).collect(), skipped_roots, projects }
}

// ---------------------------------------------------------------- cancel

fn cancel_set() -> &'static Mutex<HashSet<String>> {
    static SET: OnceLock<Mutex<HashSet<String>>> = OnceLock::new();
    SET.get_or_init(Default::default)
}

fn is_cancelled(token: &str) -> bool {
    cancel_set().lock().unwrap().contains(token)
}

/// Asks a running scan or removal to stop after the item it is on.
#[tauri::command]
pub fn cancel_build_work(token: String) {
    cancel_set().lock().unwrap().insert(token);
}

#[tauri::command]
pub async fn build_scan(app: tauri::AppHandle, extra_roots: Vec<String>, token: String) -> Result<BuildReport, String> {
    tauri::async_runtime::spawn_blocking(move || {
        let (roots, skipped) = prepare_roots(&extra_roots);
        let facts = ProjFacts::gather();
        let emit = |phase: &str, done: usize, total: usize, current: &str| {
            let _ = app.emit(
                "build-folders-progress",
                Progress { token: token.clone(), phase: phase.into(), done, total, current: current.into() },
            );
        };
        let result = scan_roots(&roots, &facts, &|| is_cancelled(&token), &emit);
        cancel_set().lock().unwrap().remove(&token);
        result.map(|p| report(roots, skipped, p)).ok_or_else(|| "Scan cancelled.".to_string())
    })
    .await
    .map_err(|e| e.to_string())?
}

