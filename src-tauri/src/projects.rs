/// How far below a search root to look for projects. Monorepos nest their
/// packages several levels down (`~/code/org/repo/packages/web`).
const SEARCH_DEPTH: usize = 8;
/// Threads measuring folder sizes at once. Each walk already runs on Jharu's
/// own pool; these only keep that pool fed while one walk waits on the disk.
const SIZE_WORKERS: usize = 4;
/// A project's "last changed" time stops looking after this many files.
const SOURCE_FILE_CAP: usize = 100_000;
/// How old a process list may be before a removal gathers it again.
const FACTS_MAX_AGE: Duration = Duration::from_secs(3);

#[cfg(target_os = "windows")]
const BIN: &str = "Recycle Bin";
#[cfg(not(target_os = "windows"))]
const BIN: &str = "Trash";

